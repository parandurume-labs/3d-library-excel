export type Copy = (typeof COPY)[Locale];

const KOREAN_CLASS_LABELS = [
  "총류", "철학", "종교", "사회과학", "언어", "자연과학", "기술과학", "예술", "문학", "역사·지리",
] as const;

export function getClassLabel(index: number, locale: Locale) {
  return locale === "ko" ? KOREAN_CLASS_LABELS[index] : undefined;
}

export function getBookDisplay(book: Book, locale: Locale) {
  return locale === "ko"
    ? { title: book.titleKo ?? book.title, author: book.authorKo ?? book.author }
    : { title: book.title, author: book.author };
}

export function getShelfDisplay(shelf: Shelf, locale: Locale) {
  if (locale !== "ko" || !shelf.id.startsWith("shelf-")) return shelf.name;
  const index = Number.parseInt(shelf.id.slice(6), 10);
  return Number.isFinite(index) ? `${String.fromCharCode(65 + (index - 1) % 5)}열 ${index}번 서가` : shelf.name;
}

export function getLocationDisplay(location: Location, locale: Locale) {
  if (locale !== "ko" || !location.id.startsWith("location-")) return location.name;
  const names = ["중앙홀", "학습관", "자료보관관"];
  const index = Number.parseInt(location.id.slice(9), 10) - 1;
  return names[index] ?? location.name;
}

/** Fills "{name}" placeholders in a copy string. */
export function fill(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => (key in values ? String(values[key]) : match));
}

export function floorLabel(floor: number | undefined, locale: Locale) {
  return floor === undefined ? "" : locale === "ko" ? `${floor}층` : `Floor ${floor}`;
}
